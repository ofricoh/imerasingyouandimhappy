  const cues = rawCues
    .map((c) => ({ id: c.id, at: c.at, start: toSeconds(c.at) }))
    .sort((a, b) => a.start - b.start);

  window.cues = cues;

  // -----------------------------
  // ACTIVE HIGHLIGHT (robust)
  // -----------------------------
  const ACTIVE_CLASS = "is-active";

  let activeId = null;
  let lastIdx = -1;

  const getElById = (id) => document.querySelector(`[data-id="${id}"]`);

  const removeActive = (id) => {
    if (!id) return;
    const el = getElById(id);
    if (el) el.classList.remove(ACTIVE_CLASS);
  };

  // IMPORTANT:
  // גם אם זה אותו id — אם האלמנט לא נמצא (כי הטקסט נטען מאוחר),
  // ננסה שוב להוסיף את המחלקה בכל tick.
  const applyActive = (id) => {
    if (!id) return;

    const el = getElById(id);
    if (el) {
      el.classList.add(ACTIVE_CLASS);
    } else {
      // Debug עדין (לא מציף): פעם בכמה זמן את כבר תראי מה חסר
      // אפשר למחוק אחרי שמסתדר
      // console.warn("[syncAudio] missing element for", id);
    }
  };

  const findCueIndex = (t) => {
    if (!cues.length) return -1;

    if (lastIdx >= 0 && lastIdx < cues.length) {
      const cur = cues[lastIdx];
      const next = cues[lastIdx + 1];

      if (t >= cur.start && (!next || t < next.start)) return lastIdx;

      if (next && t >= next.start) {
        let i = lastIdx + 1;
        while (i + 1 < cues.length && t >= cues[i + 1].start) i++;
        return i;
      }

      let j = lastIdx - 1;
      while (j >= 0 && t < cues[j].start) j--;
      return j;
    }

    let lo = 0, hi = cues.length - 1, ans = -1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (cues[mid].start <= t) {
        ans = mid;
        lo = mid + 1;
      } else {
        hi = mid - 1;
      }
    }
    return ans;
  };

  const tick = () => {
    const t = audio.currentTime;
    const idx = findCueIndex(t);

    const nextId = idx >= 0 ? cues[idx].id : null;

    // אם עברנו קיו: ננקה קודם
    if (nextId !== activeId) {
      removeActive(activeId);
      activeId = nextId;
      lastIdx = idx;
    }

    // תמיד ננסה להחיל (חשוב לטעינה מאוחרת)
    applyActive(activeId);
  };

